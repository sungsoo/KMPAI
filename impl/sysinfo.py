"""Record the execution environment (CPU, RAM, OS, Python, PyTorch, device) at run time.

    python sysinfo.py --json results/system_env.json --tex paper/generated/env.tex

Call it (or import collect()) from the experiment entry point so the values describe the
machine that actually produced the results. The .tex file defines macros for the paper:
  \\ExpCPU \\ExpRAM \\ExpOS \\ExpPython \\ExpTorch \\ExpDevice \\ExpEnvSentence
e.g. "\\textbf{실험 설정.} \\ExpEnvSentence" ->
     "실험은 Apple M3 Max CPU, 128GB RAM, Python 3.12, PyTorch 2.14.1(MPS) 환경에서 수행했다."
"""
import argparse, json, os, platform, subprocess, sys
from pathlib import Path


def _run(cmd):
    try:
        return subprocess.check_output(cmd, text=True, stderr=subprocess.DEVNULL).strip()
    except Exception:
        return ''


def cpu_name():
    if sys.platform == 'darwin':
        return _run(['sysctl', '-n', 'machdep.cpu.brand_string']) or platform.processor()
    if Path('/proc/cpuinfo').exists():
        for line in Path('/proc/cpuinfo').read_text().splitlines():
            if line.lower().startswith('model name'):
                return line.split(':', 1)[1].strip()
    return platform.processor() or platform.machine()


def ram_bytes():
    if sys.platform == 'darwin':
        v = _run(['sysctl', '-n', 'hw.memsize']); return int(v) if v.isdigit() else None
    try:
        return os.sysconf('SC_PAGE_SIZE') * os.sysconf('SC_PHYS_PAGES')
    except (ValueError, OSError, AttributeError):
        return None


def collect(device=None):
    info = {'cpu': cpu_name(), 'cpu_cores_logical': os.cpu_count(), 'ram_bytes': ram_bytes(),
            'os': f'{platform.system()} {platform.release()}', 'machine': platform.machine(),
            'macos_version': platform.mac_ver()[0] or None, 'python': platform.python_version()}
    try:
        import torch
        info['torch'] = torch.__version__
        info['cuda'] = torch.cuda.is_available()
        info['mps'] = bool(getattr(torch.backends, 'mps', None) and torch.backends.mps.is_available())
        info['device'] = device or ('cuda' if info['cuda'] else 'mps' if info['mps'] else 'cpu')
        if info['cuda']:
            info['gpu'] = torch.cuda.get_device_name(0)
    except ImportError:
        info['torch'] = None; info['device'] = device or 'cpu'
    for mod in ('numpy', 'pandas', 'matplotlib', 'scipy'):
        try:
            info[mod] = __import__(mod).__version__
        except ImportError:
            pass
    return info


def ram_text(b):
    if not b:
        return 'unknown RAM'
    gb = b / 1024 ** 3
    return f'{round(gb)}GB RAM' if gb >= 8 else f'{gb:.1f}GB RAM'


def tex(info, lang='ko'):
    py = '.'.join(info['python'].split('.')[:2])
    dev = {'mps': 'MPS', 'cuda': 'CUDA', 'cpu': 'CPU'}.get(info.get('device'), info.get('device'))
    torch = f"PyTorch {str(info['torch']).split('+')[0]}({dev})" if info.get('torch') else 'PyTorch 미설치'
    gpu = f", {info['gpu']} GPU" if info.get('gpu') else ''
    cpu = info['cpu'] if 'CPU' in info['cpu'] or 'Apple' not in info['cpu'] else info['cpu'] + ' CPU'
    sent = (f"실험은 {cpu}{gpu}, {ram_text(info['ram_bytes'])}, Python {py}, {torch} 환경에서 수행했다." if lang == 'ko'
            else f"Experiments ran on {cpu}{gpu}, {ram_text(info['ram_bytes'])}, Python {py}, {torch}.")
    esc = lambda s: str(s).replace('_', r'\_').replace('%', r'\%').replace('&', r'\&').replace('#', r'\#')
    m = {'ExpCPU': cpu, 'ExpRAM': ram_text(info['ram_bytes']), 'ExpOS': info['os'], 'ExpPython': f'Python {py}',
         'ExpTorch': torch, 'ExpDevice': dev, 'ExpEnvSentence': sent}
    return '% generated by sysinfo.py -- do not edit\n' + ''.join(rf'\providecommand{{\{k}}}{{{esc(v)}}}' + '\n' for k, v in m.items())


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--json'); ap.add_argument('--tex'); ap.add_argument('--device'); ap.add_argument('--lang', default='ko')
    ap.add_argument('--from-json', help='render --tex from an existing JSON (the machine that ran the experiments)')
    a = ap.parse_args()
    info = json.loads(Path(a.from_json).read_text()) if a.from_json else collect(a.device)
    if a.json:
        Path(a.json).parent.mkdir(parents=True, exist_ok=True); Path(a.json).write_text(json.dumps(info, indent=2, ensure_ascii=False))
    if a.tex:
        Path(a.tex).parent.mkdir(parents=True, exist_ok=True); Path(a.tex).write_text(tex(info, a.lang), encoding='utf-8')
    print(json.dumps(info, ensure_ascii=False))
